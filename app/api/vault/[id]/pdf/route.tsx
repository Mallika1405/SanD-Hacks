import React from "react";
import { Document, Page, Text, View, StyleSheet, renderToBuffer } from "@react-pdf/renderer";
import { loadEvidence } from "@/lib/vault";

export const runtime = "nodejs";
const st = StyleSheet.create({
  page: { padding: 36, fontSize: 10, fontFamily: "Helvetica" }, h1: { fontSize: 20, marginBottom: 4 }, h2: { fontSize: 13, marginTop: 14, marginBottom: 4 },
  muted: { color: "#666" }, row: { marginBottom: 2 },
});
const t = (d: any) => new Date(d).toLocaleString();

export async function GET(_: Request, { params }: { params: Promise<{ id: string }> }) {
  const { id } = await params;
  const e = await loadEvidence("id", id);
  if (!e) return new Response("not found", { status: 404 });
  const chips = Object.entries(e.chips as Record<string, string>);
  const doc = (
    <Document>
      <Page size="A4" style={st.page}>
        <Text style={st.h1}>Haven incident report</Text>
        <Text style={st.muted}>{e.session.user_name} · {e.session.mode} session · {t(e.session.started_at)}</Text>
        <Text style={st.muted}>Generated by Haven. Haven does not replace 911. Facts below were captured automatically and may be incomplete.</Text>
        <Text style={st.h2}>Description captured</Text>
        {chips.length ? chips.map(([k, v]) => <Text key={k} style={st.row}>{k.replace("_", " / ")}: {v}</Text>) : <Text style={st.muted}>None captured.</Text>}
        <Text style={st.h2}>Timeline</Text>
        {(e.events as any[]).map((ev, i) => <Text key={i} style={st.row}>{t(ev.created_at)}  {ev.note ?? ev.kind}</Text>)}
        <Text style={st.h2}>Alerts</Text>
        {(e.alerts as any[]).map((a, i) => <Text key={i} style={st.row}>{t(a.created_at)}  {a.kind} alert ({a.status}){a.place_text ? ` ${a.place_text}` : ""}</Text>)}
        <Text style={st.h2}>Transcript</Text>
        {(e.transcript as any[]).map((l, i) => <Text key={i} style={st.row}>{l.role === "user" ? "Her" : "Haven"}: {l.text}</Text>)}
        <Text style={st.h2}>Audio clips</Text>
        {(e.clips as any[]).map((c, i) => <Text key={i} style={st.row}>{t(c.created_at)}  {c.url}</Text>)}
        <Text style={st.h2}>GPS trail ({e.trail.length} points)</Text>
        {(e.trail as any[]).filter((_, i) => i % Math.max(1, Math.floor(e.trail.length / 25)) === 0).map((p, i) => <Text key={i} style={st.row}>{t(p.recorded_at)}  {p.lat.toFixed(5)}, {p.lng.toFixed(5)}</Text>)}
      </Page>
    </Document>
  );
  const buf = await renderToBuffer(doc);
  return new Response(new Uint8Array(buf), { headers: { "Content-Type": "application/pdf", "Content-Disposition": `attachment; filename="haven-report-${id.slice(0, 8)}.pdf"` } });
}
